
// A teacher wants to calculate the sums of both diagonals of a square matrix.

public class DiagonalSum {
    public static void main(String[] args) {
        int[][] matrix = {
            {10, 20, 30},
            {40, 50, 60},
            {70, 80, 90}
        };

        for(int i=0; i<matrix.length; i++) {
            System.out.println(matrix[i][0]);
        }

    }
}