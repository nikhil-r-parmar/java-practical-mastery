
public class DataTypes {
    public static void main (String args[])  {
        int wholeNo = 250;   // integer/whole number
        // similar - byte

        long LongNo = 9876543210l;    // Long integer
        // similar - short

        float number = 25.75f;   // floating/decimal number
        double number2 = 125.678;    // long floating number

        char a = 'A';   // single character
        boolean activity = true;     // boolean value
        String name = "NIKHIL";      // string/text value

        // Literals:
        String name2 = "NickyP";
        // here NickyP is literal & name is variable.

        System.out.println(wholeNo);
        System.out.println(LongNo);
        System.out.println(number);
        System.out.println(number2);
        System.out.println(a);
        System.out.println(activity);
        System.out.println(name);
        System.out.println(name2);
    }
}