public class EscapeChars {
    public static void main(String args[]) {

        // Name inside duble quotes
        System.out.print("Developer: \"Nikhil\" \n");

        // message on new line
        System.out.print("Message: Keep Learning! \n");

        // using tab space
        System.out.println("GitHub: \tnikhil-r-parmar");

        // file path
        System.out.println("D:\\java-practical-mastery\\1-Variables_and_DataTypes\\EscapeChars.java");

        // Single & Double Quote
        System.out.println("'");
        System.out.println("\"");

    }
}