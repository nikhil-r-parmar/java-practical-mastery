public class StockCounter {
    public static void main(String args[]) {
        int stock = 50;
        System.out.println(stock);
        
        System.out.println(++stock);

        System.out.println(stock--);

        --stock;
        System.out.println(stock);

        stock--;
        System.out.println(stock);

        System.out.println(+stock);

        System.out.println(-stock);

    }
}